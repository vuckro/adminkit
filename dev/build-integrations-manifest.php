<?php
/**
 * Compile `inc/generated/integrations-manifest.php` from `inc/integrations/{plugins,themes}/* /class-*.php`.
 *
 * Avoids runtime `glob()` and `require_once` on all 28 adapter files during
 * frontend, REST, cron, and non-matching admin requests.
 *
 * Usage:
 *   php dev/build-integrations-manifest.php          # write inc/generated/integrations-manifest.php
 *   php dev/build-integrations-manifest.php --check  # exit 1 if out of sync
 *
 * @package AdminKit
 */

define( 'ABSPATH', __DIR__ . '/' );
define( 'ADMINKIT_PATH', dirname( __DIR__ ) . '/' );

$out_path = ADMINKIT_PATH . 'inc/generated/integrations-manifest.php';
$files    = glob( ADMINKIT_PATH . 'inc/integrations/{plugins,themes}/*/class-*.php', GLOB_BRACE );

if ( ! is_array( $files ) || empty( $files ) ) {
	fwrite( STDERR, "No integration adapter classes found.\n" );
	exit( 1 );
}

/**
 * Extract the normalized return expression from `public static function is_active()`.
 *
 * @param string $source PHP source of the adapter file.
 * @param string $path   File path for error reporting.
 * @return string
 */
function ak_extract_is_active_expr( $source, $path ) {
	$tokens = token_get_all( $source );
	$count  = count( $tokens );
	$i      = 0;

	while ( $i < $count ) {
		$tok = $tokens[ $i ];
		if ( is_array( $tok ) && T_FUNCTION === $tok[0] ) {
			$j = $i + 1;
			while ( $j < $count && is_array( $tokens[ $j ] ) && in_array( $tokens[ $j ][0], array( T_WHITESPACE, T_COMMENT, T_DOC_COMMENT ), true ) ) {
				++$j;
			}
			if ( $j < $count && is_array( $tokens[ $j ] ) && T_STRING === $tokens[ $j ][0] && 'is_active' === $tokens[ $j ][1] ) {
				while ( $j < $count && '{' !== $tokens[ $j ] ) {
					++$j;
				}
				if ( $j < $count && '{' === $tokens[ $j ] ) {
					$depth = 1;
					++$j;
					$body = array();
					while ( $j < $count && $depth > 0 ) {
						$t = $tokens[ $j ];
						if ( '{' === $t ) {
							++$depth;
						} elseif ( '}' === $t ) {
							--$depth;
							if ( 0 === $depth ) {
								break;
							}
						}
						if ( ! is_array( $t ) || ! in_array( $t[0], array( T_COMMENT, T_DOC_COMMENT ), true ) ) {
							$body[] = is_array( $t ) ? $t[1] : $t;
						}
						++$j;
					}
					$expr = trim( implode( '', $body ) );
					$expr = preg_replace( '/^return\s+/', '', $expr );
					$expr = rtrim( trim( (string) $expr ), ';' );
					$expr = trim( (string) preg_replace( '/\s+/', ' ', $expr ) );
					if ( '' === $expr ) {
						throw new RuntimeException( 'Empty is_active() in ' . $path );
					}
					return $expr;
				}
			}
		}
		++$i;
	}

	throw new RuntimeException( 'Missing is_active() in ' . $path );
}

$entries = array();
foreach ( $files as $file ) {
	$src   = (string) file_get_contents( $file );
	$slug  = substr( basename( $file, '.php' ), strlen( 'class-' ) );
	$group = basename( dirname( $file, 2 ) );
	$rel   = 'integrations/' . $group . '/' . $slug . '/' . basename( $file );
	$class = 'AdminKit_Integration_' . str_replace( '-', '_', ucwords( $slug, '-' ) );
	$type  = 'themes' === $group ? 'theme' : 'plugin';

	// Adapters that hook frontend toolbar/theme/shadow-DOM/style bypasses must run on ! is_admin().
	$frontend = (bool) preg_match( "/['\"]frontend['\"]|\\bwp_head\\b|\\bwp_enqueue_scripts\\b|adminkit\\/toolbar_icons/", $src );
	$expr     = ak_extract_is_active_expr( $src, $rel );

	$entries[ $slug ] = array(
		'file'     => $rel,
		'class'    => $class,
		'type'     => $type,
		'frontend' => $frontend,
		'active'   => $expr,
	);
}

ksort( $entries );

$lines   = array();
$lines[] = '<?php';
$lines[] = '/**';
$lines[] = ' * Precompiled integration adapter manifest (replaces runtime glob + eager loading).';
$lines[] = ' * Generated by `php dev/build-integrations-manifest.php` — DO NOT EDIT.';
$lines[] = ' *';
$lines[] = ' * @package AdminKit';
$lines[] = ' */';
$lines[] = '';
$lines[] = "defined( 'ABSPATH' ) || exit;";
$lines[] = '';
$lines[] = 'final class AdminKit_Integrations_Manifest {';
$lines[] = '';
$lines[] = "\t/** @var array<string, array{file:string,class:string,type:string,frontend:bool}> */";
$lines[] = "\tconst ITEMS = array(";

foreach ( $entries as $slug => $entry ) {
	$lines[] = "\t\t" . var_export( (string) $slug, true ) . ' => array(';
	$lines[] = "\t\t\t'file'     => " . var_export( $entry['file'], true ) . ',';
	$lines[] = "\t\t\t'class'    => " . var_export( $entry['class'], true ) . ',';
	$lines[] = "\t\t\t'type'     => " . var_export( $entry['type'], true ) . ',';
	$lines[] = "\t\t\t'frontend' => " . ( $entry['frontend'] ? 'true' : 'false' ) . ',';
	$lines[] = "\t\t),";
}

$lines[] = "\t);";
$lines[] = '';
$lines[] = "\t/**";
$lines[] = "\t * Zero-I/O host activation check mirrored from each adapter's `is_active()`.";
$lines[] = "\t *";
$lines[] = "\t * @param string \$slug Integration slug.";
$lines[] = "\t * @return bool";
$lines[] = "\t */";
$lines[] = "\tpublic static function is_host_active( \$slug ) {";
$lines[] = "\t\tswitch ( \$slug ) {";

foreach ( $entries as $slug => $entry ) {
	$lines[] = "\t\t\tcase " . var_export( (string) $slug, true ) . ':';
	$lines[] = "\t\t\t\treturn " . $entry['active'] . ';';
}

$lines[] = "\t\t\tdefault:";
$lines[] = "\t\t\t\treturn false;";
$lines[] = "\t\t}";
$lines[] = "\t}";
$lines[] = '}';
$lines[] = '';
$lines[] = 'return AdminKit_Integrations_Manifest::ITEMS;';
$lines[] = '';

$expected = implode( "\n", $lines );
$check    = in_array( '--check', $argv, true );

if ( $check ) {
	$actual = is_file( $out_path ) ? (string) file_get_contents( $out_path ) : '';
	if ( $actual !== $expected ) {
		fwrite( STDERR, "inc/generated/integrations-manifest.php is out of sync. Run: php dev/build-integrations-manifest.php\n" );
		exit( 1 );
	}
	echo 'OK: inc/generated/integrations-manifest.php matches ' . count( $entries ) . " integration adapters.\n";
	exit( 0 );
}

if ( ! is_dir( dirname( $out_path ) ) ) {
	mkdir( dirname( $out_path ), 0755, true );
}
file_put_contents( $out_path, $expected );
echo 'Wrote inc/generated/integrations-manifest.php (' . count( $entries ) . " adapters).\n";
