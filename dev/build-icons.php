<?php
/**
 * Compile assets/icons/lucide.json + AdminKit_Icons::ALIASES into an OPcache-ready
 * PHP constant map (`inc/generated/lucide-paths.php`).
 *
 * Usage:
 *   php dev/build-icons.php          # write inc/generated/lucide-paths.php
 *   php dev/build-icons.php --check  # exit 1 if out of sync
 *
 * @package AdminKit
 */

define( 'ABSPATH', __DIR__ . '/' );
define( 'ADMINKIT_PATH', dirname( __DIR__ ) . '/' );

require_once ADMINKIT_PATH . 'inc/class-icons.php';

$json_path = ADMINKIT_PATH . 'assets/icons/lucide.json';
$out_path  = ADMINKIT_PATH . 'inc/generated/lucide-paths.php';

$catalog = json_decode( (string) file_get_contents( $json_path ), true );
if ( ! is_array( $catalog ) || empty( $catalog ) ) {
	fwrite( STDERR, "Failed to decode {$json_path}\n" );
	exit( 1 );
}

$paths = array();
foreach ( AdminKit_Icons::ALIASES as $role => $name ) {
	if ( isset( $catalog[ $name ] ) ) {
		$paths[ $role ] = $catalog[ $name ];
	}
}
$paths += $catalog;

$lines   = array();
$lines[] = '<?php';
$lines[] = '/**';
$lines[] = ' * Precompiled Lucide SVG inner paths + role aliases (served from OPcache SHM).';
$lines[] = ' * Generated by `php dev/build-icons.php` from `assets/icons/lucide.json` — DO NOT EDIT.';
$lines[] = ' *';
$lines[] = ' * @package AdminKit';
$lines[] = ' */';
$lines[] = '';
$lines[] = "defined( 'ABSPATH' ) || exit;";
$lines[] = '';
$lines[] = 'final class AdminKit_Lucide_Paths {';
$lines[] = "\tconst MAP = array(";
foreach ( $paths as $key => $markup ) {
	$lines[] = "\t\t" . var_export( (string) $key, true ) . ' => ' . var_export( (string) $markup, true ) . ',';
}
$lines[] = "\t);";
$lines[] = '}';
$lines[] = '';
$lines[] = 'return AdminKit_Lucide_Paths::MAP;';
$lines[] = '';

$expected = implode( "\n", $lines );
$check    = in_array( '--check', $argv, true );

if ( $check ) {
	$actual = is_file( $out_path ) ? (string) file_get_contents( $out_path ) : '';
	if ( $actual !== $expected ) {
		fwrite( STDERR, "inc/generated/lucide-paths.php is out of sync with assets/icons/lucide.json. Run: php dev/build-icons.php\n" );
		exit( 1 );
	}
	echo 'OK: inc/generated/lucide-paths.php matches assets/icons/lucide.json (' . count( $paths ) . " entries).\n";
	exit( 0 );
}

if ( ! is_dir( dirname( $out_path ) ) ) {
	mkdir( dirname( $out_path ), 0755, true );
}
file_put_contents( $out_path, $expected );
echo 'Wrote inc/generated/lucide-paths.php (' . count( $paths ) . " entries).\n";
